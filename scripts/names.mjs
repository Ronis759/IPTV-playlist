/** Мелкая нормализация ключа: нижний регистр, убрать качество в скобках. */
export function nameKey(name) {
  return String(name || '')
    .toLowerCase()
    .replace(/\((?:sd|hd|[0-9]{3,4}[pi]|[0-9]{3,4}x[0-9]{3,4})\)/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Русское название по ключу, если известно. */
export function russianName(name) {
  return RU_NAMES[nameKey(name)] || null;
}
